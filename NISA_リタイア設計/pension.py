"""厚生年金の推計（1981年生まれ=45歳。22歳就職ならほぼ全期間が2003年4月の総報酬制以降）"""

# 報酬比例部分 = 平均標準報酬額 × 5.481/1000 × 加入月数
# 年収900万を45歳で得ている人の生涯賃金カーブを仮定
career = [  # (期間年数, その期間の平均標準報酬額 月額万円)
    (8,  35),   # 22-30歳
    (10, 50),   # 30-40歳
    (10, 68),   # 40-50歳
    (10, 75),   # 50-60歳  ※標準報酬月額の上限65万＋賞与を月割りした水準
]
months = sum(y*12 for y,_ in career)
avg = sum(y*12*m for y,m in career) / months
hoshu = avg * 5.481/1000 * months          # 万円/年
kiso  = 83.0                                # 老齢基礎年金 満額（40年納付）
print(f"加入期間 {months}か月（{months//12}年） / 平均標準報酬額 {avg:.1f}万円")
print(f"報酬比例部分 {hoshu:.0f}万円 + 老齢基礎年金 {kiso:.0f}万円 = 1人あたり {hoshu+kiso:.0f}万円/年"
      f"（月 {(hoshu+kiso)/12:.1f}万円）")
print(f"夫婦2人分 = {2*(hoshu+kiso):.0f}万円/年（月 {2*(hoshu+kiso)/12:.1f}万円）\n")

print("【感度】生涯平均標準報酬額がぶれた場合の夫婦合計（65歳から・年額）")
for a in (50, 55, 58.2, 62, 65):
    one = a*5.481/1000*months + kiso
    print(f"  平均 {a:>4.1f}万円/月 → 1人 {one:5.0f}万円 / 夫婦 {2*one:5.0f}万円（月 {2*one/12:4.1f}万円）")

print("\n【繰下げの選択肢】夫婦合計・年額")
base = 2*(hoshu+kiso)
print(f"  (a) 2人とも65歳受給            : {base:5.0f}万円/年  ← 60-65歳の5年を資産でつなぐ")
print(f"  (b) 2人とも70歳受給（+42%）     : {base*1.42:5.0f}万円/年  ← 60-70歳の10年を資産でつなぐ")
print(f"  (c) 1人だけ70歳繰下げ          : 65-70歳 {base/2:.0f}万 → 70歳〜 {base/2*1.42+base/2:5.0f}万円/年")
