# 既定フォント（東アジア）
def set_base_font(name, size):
    st = doc.styles["Normal"]
    st.font.name = name
    st.font.size = Pt(size)
    rpr = st.element.get_or_add_rPr()
    rf = rpr.find(qn('w:rFonts'))
    if rf is None:
        rf = OxmlElement('w:rFonts'); rpr.append(rf)
    rf.set(qn('w:eastAsia'), name)
    rf.set(qn('w:ascii'), name)
    rf.set(qn('w:hAnsi'), name)
set_base_font(JP, 10.5)

# 余白
for s in doc.sections:
    s.top_margin = Cm(1.8); s.bottom_margin = Cm(1.6)
    s.left_margin = Cm(2.0); s.right_margin = Cm(2.0)

def _ea(run, name):
    rpr = run._element.get_or_add_rPr()
    rf = rpr.find(qn('w:rFonts'))
    if rf is None:
        rf = OxmlElement('w:rFonts'); rpr.append(rf)
    rf.set(qn('w:eastAsia'), name); rf.set(qn('w:ascii'), name); rf.set(qn('w:hAnsi'), name)

def para(runs, align=None, before=2, after=4, size=10.5, line=1.32, font=JP):
    p = doc.add_paragraph()
    if align: p.alignment = align
    pf = p.paragraph_format
    pf.space_before = Pt(before); pf.space_after = Pt(after)
    pf.line_spacing = line
    if isinstance(runs, str): runs = [(runs, {})]
    for text, o in runs:
        r = p.add_run(text)
        r.font.size = Pt(o.get("size", size))
        r.font.bold = o.get("bold", False)
        r.font.italic = o.get("italic", False)
        if "color" in o: r.font.color.rgb = o["color"]
        _ea(r, o.get("font", font))
    return p

def rule():
    p = doc.add_paragraph(); p.paragraph_format.space_before = Pt(2); p.paragraph_format.space_after = Pt(2)
    pPr = p._p.get_or_add_pPr(); pb = OxmlElement('w:pBdr'); bottom = OxmlElement('w:bottom')
    bottom.set(qn('w:val'),'single'); bottom.set(qn('w:sz'),'6'); bottom.set(qn('w:space'),'1'); bottom.set(qn('w:color'),'BBBBBB')
    pb.append(bottom); pPr.append(pb)

def slide_cue(nlabel, title, tm):
    p = doc.add_paragraph()
    pf = p.paragraph_format; pf.space_before = Pt(11); pf.space_after = Pt(3); pf.keep_with_next = True
    # shading
    pPr = p._p.get_or_add_pPr(); sh = OxmlElement('w:shd')
    sh.set(qn('w:val'),'clear'); sh.set(qn('w:fill'),'EEF4F0'); pPr.append(sh)
    r1 = p.add_run(f"■ {nlabel}"); r1.font.bold = True; r1.font.size = Pt(11); r1.font.color.rgb = GREEN; _ea(r1, JP)
    r2 = p.add_run(f"　{title}"); r2.font.bold = True; r2.font.size = Pt(11); _ea(r2, JP)
    r3 = p.add_run(f"　〔目安 {tm}〕"); r3.font.size = Pt(9.5); r3.font.color.rgb = GOLD; _ea(r3, JP)

def section(title):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(12); p.paragraph_format.space_after = Pt(4)
    r = p.add_run(title); r.font.bold = True; r.font.size = Pt(13); r.font.color.rgb = GREEN; _ea(r, JP)

def speech(text):
    para([(text, {"size":10.5})], line=1.4, after=2)

def direction(text):
    para([("（"+text+"）", {"size":9.5, "color":GRAY, "italic":True})], before=0, after=2)

