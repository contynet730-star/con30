def H1(text):
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text); r.font.size = Pt(20); r.font.bold = True; r.font.color.rgb = NAVY
    r.font.name='メイリオ'; r._element.rPr.rFonts.set(qn('w:eastAsia'),'メイリオ')

def H2(text):
    p = doc.add_paragraph()
    r = p.add_run(text); r.font.size = Pt(14); r.font.bold = True; r.font.color.rgb = NAVY
    r.font.name='メイリオ'; r._element.rPr.rFonts.set(qn('w:eastAsia'),'メイリオ')
    p.paragraph_format.space_before=Pt(12); p.paragraph_format.space_after=Pt(4)

def P(text, size=10.5, bold=False, color=None, indent=0):
    p = doc.add_paragraph()
    if indent: p.paragraph_format.left_indent = Cm(indent)
    p.paragraph_format.line_spacing = 1.45; p.paragraph_format.space_after = Pt(2)
    r = p.add_run(text); r.font.size = Pt(size); r.font.bold = bold
    if color: r.font.color.rgb = color
    r.font.name='メイリオ'; r._element.rPr.rFonts.set(qn('w:eastAsia'),'メイリオ')

def HR():
    p=doc.add_paragraph()
    p.paragraph_format.space_before=Pt(6); p.paragraph_format.space_after=Pt(6)
    r=p.add_run('─'*45); r.font.color.rgb=GRAY; r.font.size=Pt(9)

def add_q(num, question, conclusion, perspectives, final):
    """Q+A 3段構成"""
    # Q
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(14); p.paragraph_format.space_after = Pt(3)
    r1 = p.add_run(f'Q{num}.  ')
    r1.font.size = Pt(12); r1.font.bold = True; r1.font.color.rgb = ORANGE
    r1.font.name='メイリオ'; r1._element.rPr.rFonts.set(qn('w:eastAsia'),'メイリオ')
    r2 = p.add_run(question)
    r2.font.size = Pt(12); r2.font.bold = True; r2.font.color.rgb = NAVY
    r2.font.name='メイリオ'; r2._element.rPr.rFonts.set(qn('w:eastAsia'),'メイリオ')

    # ①結論
    p_a = doc.add_paragraph()
    p_a.paragraph_format.left_indent = Cm(0.6); p_a.paragraph_format.line_spacing = 1.4
    p_a.paragraph_format.space_after = Pt(3)
    rA = p_a.add_run('① まず端的に　── ')
    rA.font.size = Pt(10.5); rA.font.bold = True; rA.font.color.rgb = GREEN
    rA.font.name='メイリオ'; rA._element.rPr.rFonts.set(qn('w:eastAsia'),'メイリオ')
    rAt = p_a.add_run(conclusion)
    rAt.font.size = Pt(10.5)
    rAt.font.name='メイリオ'; rAt._element.rPr.rFonts.set(qn('w:eastAsia'),'メイリオ')

    # ②複数視点
    p_h = doc.add_paragraph()
    p_h.paragraph_format.left_indent = Cm(0.6); p_h.paragraph_format.space_after = Pt(2)
    rH = p_h.add_run('② 複数の専門家視点から')
    rH.font.size = Pt(10.5); rH.font.bold = True; rH.font.color.rgb = PURPLE
    rH.font.name='メイリオ'; rH._element.rPr.rFonts.set(qn('w:eastAsia'),'メイリオ')

    for view_name, view_text in perspectives:
        p_v = doc.add_paragraph()
        p_v.paragraph_format.left_indent = Cm(1.2); p_v.paragraph_format.line_spacing = 1.4
        p_v.paragraph_format.space_after = Pt(2)
        rVn = p_v.add_run(f'■ {view_name}：')
        rVn.font.size = Pt(10); rVn.font.bold = True; rVn.font.color.rgb = TEAL
        rVn.font.name='メイリオ'; rVn._element.rPr.rFonts.set(qn('w:eastAsia'),'メイリオ')
        rVt = p_v.add_run(view_text)
        rVt.font.size = Pt(10)
        rVt.font.name='メイリオ'; rVt._element.rPr.rFonts.set(qn('w:eastAsia'),'メイリオ')

    # ③指導主事の結論
    p_f = doc.add_paragraph()
    p_f.paragraph_format.left_indent = Cm(0.6); p_f.paragraph_format.line_spacing = 1.4
    p_f.paragraph_format.space_after = Pt(3); p_f.paragraph_format.space_before = Pt(3)
    rF = p_f.add_run('③ 指導主事としての結論　── ')
    rF.font.size = Pt(10.5); rF.font.bold = True; rF.font.color.rgb = ORANGE
    rF.font.name='メイリオ'; rF._element.rPr.rFonts.set(qn('w:eastAsia'),'メイリオ')
    rFt = p_f.add_run(final)
    rFt.font.size = Pt(10.5)
    rFt.font.name='メイリオ'; rFt._element.rPr.rFonts.set(qn('w:eastAsia'),'メイリオ')

